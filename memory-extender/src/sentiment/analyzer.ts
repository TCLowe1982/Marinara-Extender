// ── JSON extraction (handles markdown-fenced responses) ────────────────────

function parseEmotions(raw: unknown): EmotionWeight[] | undefined {
  if (!Array.isArray(raw) || raw.length === 0) return undefined;
  const result: EmotionWeight[] = [];
  for (const item of raw) {
    if (typeof item === "object" && item !== null &&
        typeof (item as Record<string, unknown>).emotion === "string" &&
        typeof (item as Record<string, unknown>).weight === "number") {
      result.push({
        emotion: (item as { emotion: Emotion; weight: number }).emotion,
        weight:  (item as { emotion: Emotion; weight: number }).weight,
      });
    }
  }
  return result.length > 0 ? result : undefined;
}

/** The candidate JSON strings in a raw reply: the bare text, then a fenced block. */
function jsonAttempts(raw: string): string[] {
  return [
    String(raw ?? "").trim(),
    String(raw ?? "").match(/```(?:json)?\s*([\s\S]*?)```/i)?.[1]?.trim() ?? "",
  ];
}

/**
 * Did the model legally DECLINE, as opposed to producing unparseable output?
 *
 * EXPORTED BECAUSE THE DISTINCTION DECIDES A PRE-REGISTERED TEST. Both outcomes
 * yield no beat, so the pipeline does not care — but "JSON validity must not drop a
 * point" is a ship condition for the prompt rewrite (vikj), and a prompt that
 * declines correctly would be scored as invalid JSON if declines and failures were
 * indistinguishable. That would penalise a draft for obeying its own instruction.
 *
 * Deliberately not logged per chunk: the analyzer avoids per-chunk output because it
 * breaks the import progress bar. Callers that want decline telemetry count it.
 */
export function isDeclineResponse(raw: string): boolean {
  for (const attempt of jsonAttempts(raw)) {
    if (!attempt) continue;
    try {
      const parsed = JSON.parse(attempt) as Record<string, unknown>;
      if (parsed.no_beat === true) return true;
    } catch { /* try next */ }
  }
  return false;
}

function parseAnalysisJson(
  raw: string,
  sourceText: string,
  exempt: string[] | null = null,
  chatId?: string,
): BeatAnalysis | null {
  const attempts = jsonAttempts(raw);

  for (const attempt of attempts) {
    if (!attempt) continue;
    try {
      const parsed = JSON.parse(attempt) as Record<string, unknown>;

      // THE DECLINE PATH (vikj, Mari's ruling). Until this existed, the prompt told
      // the model "the chunk has no beat — say so rather than reaching for a
      // remembered phrase" and the schema gave it nowhere to say so. The only way
      // to comply was to emit malformed JSON, which made compliance indistinguishable
      // from failure — an advisory guard doing no work, the exact class ruled against
      // on 2026-08-04.
      //
      // The shape is `{"no_beat": true}`. `reason` is TOLERATED AND NEVER REQUIRED,
      // and that is deliberate: a mandatory freeform justification is a fresh
      // boilerplate surface bolted onto every decline, generated by a model that
      // copies whatever phrasing is nearest. Telemetry about declines belongs in
      // code, not in a field the model has to fill.
      //
      // Returns null, the same value a parse failure returns, because downstream
      // "no beat" is one outcome with one meaning. What changes is that a decline is
      // now a SUCCESSFUL parse — so it stops being counted as invalid JSON, and the
      // model has a legal way to obey the instruction.
      if (parsed.no_beat === true) return null;

      if (typeof parsed.motivation !== "string") continue;
      if (typeof parsed.relational_dynamics !== "string") continue;
      if (typeof parsed.outcome !== "string") continue;
      // pifl: the model copies the prompt's own example when it cannot be specific.
      // Measured before the fix: 792 beats (9% of the store) echoed one, 669 of them
      // the single sentence used to ILLUSTRATE "two different moments can never
      // produce the same sentence". Rewording the examples is necessary but is not a
      // guarantee — a model under-instructed by a long chunk reaches for whatever
      // phrasing is nearest, and the prompt is nearest. This is the guarantee.
      if (rejectAsEcho(parsed.motivation, sourceText)) return null;
      // epf4: the model invents a partner when the chunk gives it none, and the
      // invented name lands in the entry summary the loader injects. Neutralised
      // rather than rejected — the beat is a real moment, only the noun is false.
      // Inert when `exempt` is null (exemptions unavailable): silence, not accusation.
      const guard = (v: string, field: string) => guardField(v, sourceText, exempt, { field, chatId });
      return {
        motivation:        guard(parsed.motivation.trim(), "motivation"),
        relationalDynamics: guard(parsed.relational_dynamics.trim(), "relationalDynamics"),
        outcome:           guard(parsed.outcome.trim(), "outcome"),
        subpattern:        typeof parsed.subpattern === "string" ? parsed.subpattern : undefined,
        emotions:          parseEmotions(parsed.emotions),
        subtext:           typeof parsed.subtext === "string" && parsed.subtext.trim()
                             ? parsed.subtext.trim() : undefined,
        salience:          typeof parsed.salience === "number"
                             ? Math.min(1, Math.max(0, parsed.salience))
                             : 0.5,
        subject:           typeof parsed.subject === "string" && parsed.subject.trim()
                             ? parsed.subject.trim() : undefined,
        thread:            typeof parsed.thread === "string" && parsed.thread.trim()
                             ? parsed.thread.trim() : undefined,
      };
    } catch {
      // try next
    }
  }
  return null;
}

// ── Local model (Ollama or any OpenAI-compatible local server) ────────────

async function callLocal(systemPrompt: string, userPrompt: string): Promise<string | null> {
  if (!localEnabled()) return null;  // explicitly disabled — skip
  const base = localUrl();
  const model = localModel();

  try {
    const res = await fetch(`${base}/chat/completions`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        model,
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user",   content: userPrompt },
        ],
        temperature: 0.2,
        stream: false,
        response_format: { type: "json_object" }, // force JSON; avoid prose fallback
      }),
      signal: AbortSignal.timeout(60_000),
    });
    if (!res.ok) return null;
    const json = (await res.json()) as { choices?: Array<{ message?: { content?: string } }> };
    return json?.choices?.[0]?.message?.content ?? null;
  } catch {
    return null;
  }
}

// ── External API fallback ─────────────────────────────────────────────────

async function callExternal(systemPrompt: string, userPrompt: string): Promise<string> {
  const auth = getCachedAuth();
  if (!auth) {
    throw new Error(
      "Analyzer: local Ollama model unavailable and no API key set. Run Ollama (MARINARA_EXTENDER_LOCAL_URL/LOCAL_MODEL) or set MARINARA_EXTENDER_API_KEY.",
    );
  }
  const upstream = externalUpstream();
  const model = externalModel();

  const res = await fetchWithBackoff(`${upstream}/v1/chat/completions`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: auth },
    body: JSON.stringify({
      model,
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user",   content: userPrompt },
      ],
      temperature: 0.2,
      max_tokens: 600,
    }),
  });
  if (!res.ok) throw new Error(`Analyzer external API failed (${res.status}): ${await res.text()}`);
  const json = (await res.json()) as { choices?: Array<{ message?: { content?: string } }> };
  return json?.choices?.[0]?.message?.content ?? "";
}

async function callLlm(systemPrompt: string, userPrompt: string): Promise<string> {
  const local = await callLocal(systemPrompt, userPrompt);
  if (local !== null) return local;
  // No per-chunk warn here — it would break the progress bar; the pipeline's
  // progress reporter surfaces per-chunk status instead.
  return callExternal(systemPrompt, userPrompt);
}

