const CHALLENGER_FIELDS: Record<Emotion, [string, string, string]> = {
  fear:          ["What is this person afraid of? What threat is activating it?", "How is the fear shaping the relationship right now?", "What does this signal about what happens next?"],
  shame:         ["What belief about the self was triggered, and by what?", "Is shame causing hiding, self-attack, or a bid for reassurance?", "How will they behave next, toward themselves or others?"],
  hope:          ["What are they hoping for, and what makes it feel possible now?", "How is the hope changing what they risk saying?", "What does this suggest they will reach for next?"],
  desire:        ["What do they want, specifically, in this moment?", "How is the wanting being offered, hidden, or negotiated?", "What does this set up between them?"],
  relief:        ["What stopped being a threat, and how long had it been one?", "What does the relief let them do that they could not before?", "What changes now that the pressure is off?"],
  vulnerability: ["What did they expose that they could have kept back?", "What is the exposure asking of the other person?", "What becomes possible or risky after this?"],
  trust:         ["What are they trusting the other with, concretely?", "What did the other do to earn or test it?", "What does extending it commit them to?"],
  anger:         ["What was violated, and what is the anger protecting?", "Is the anger creating distance or demanding to be seen?", "Where does this leave them next?"],
  joy:           ["What is the joy actually about, in its particulars?", "How is it being shared, performed, or withheld?", "What does it make more likely between them?"],
  dysregulation: ["What is underneath the surface behaviour?", "How is it landing on the other person?", "What happens if it is not met?"],
};

const CHALLENGER_SUBTEXT = `- subtext: only if the chunk contains sexual or physically intimate content — name the emotional function of that content (trust-building, vulnerability, power exchange, comfort-seeking, avoidance). Otherwise omit it.`;

/**
 * THE SECOND ASK (5x5y). Appended to the user prompt on ONE retry, when the intimacy
 * detector says the chunk warrants a subtext and the first answer omitted it.
 *
 * It carries NO EXAMPLE, deliberately. The prompt law (pifl) is that examples are
 * gravitational mass regardless of sign, and this instruction fires precisely when
 * the model has already shown it has nothing to say — the moment it is most likely to
 * reach for the nearest available phrasing. An illustration here would be echoed
 * straight into the store, and it would be echoed into the one field we have no
 * historical baseline for.
 *
 * THE ESCAPE HATCH IS LOAD-BEARING, not politeness. Enforcement whose only accepted
 * answer is a filled field does not produce subtext, it produces INVENTED subtext —
 * which is epf4 again, in a field created to hold a judgement. So a second refusal is
 * an allowed outcome, and it is recorded rather than punished. What we are buying is
 * a rate we can read, not a field that is never empty.
 */
const SUBTEXT_RETRY = `
The chunk you just analyzed contains physically intimate content, and your answer omitted the subtext field.

Answer again in the same JSON shape, and this time include subtext: name what the physical content is doing emotionally for these two people in THIS moment — what it builds, tests, asks for, or avoids.

If the chunk genuinely does not show you that, omit the field again. Do not fill it with something plausible.`;

/** Exposed for the prompt catalogue — every prompt this system sends must be readable. */
export function subtextRetryInstruction(): string {
  return SUBTEXT_RETRY.trim();
}

// The nine keys VERBATIM from the taxonomy the parser documents — the draft doc's
// first revision listed five keys that do not exist, from memory, and was caught
// by reading this file. Schema-from-memory is the exact failure the packet warns
// about; the compressed list must never drift from dysregulationPrompt's.
const CHALLENGER_SUBPATTERN = `- subpattern: which structural pattern fits best — bpd_testing, anxious_protest, avoidant_withdrawal, dissociation, catastrophizing, idealization, devaluation, emotional_flooding, or shutdown. Pick one key exactly as written, or omit the field.`;

function challengerPrompt(emotion: Emotion, structuralSubpatterns: string[]): string {
  const [m, r, o] = CHALLENGER_FIELDS[emotion];
  const dysreg = emotion === "dysregulation";
  const structuralHint = dysreg && structuralSubpatterns.length > 0
    ? `\nThe classifier also detected these structural signals in the text: ${structuralSubpatterns.join(", ")}. Weight these in your subpattern assessment.`
    : "";

  return `You are analyzing a moment of ${emotion.toUpperCase()} in a conversation.
${structuralHint}
- motivation: ${m}
- relational_dynamics: ${r}
- outcome: ${o}
${dysreg ? CHALLENGER_SUBPATTERN + "\n" : ""}${CHALLENGER_SUBTEXT}

- motivation must name the SPECIFIC content of THIS moment — what was actually said, feared, wanted, or done — so two different moments can never produce the same sentence. Genre descriptions are forbidden.
  TOO VAGUE, because it could describe a hundred different moments:
    ${BAIT.vague.map((e) => `"${e.text}"`).join(" / ")}
  SPECIFIC ENOUGH, because only one moment could have produced it:
${BAIT.specific.map((e) => `    "${e.text}"`).join("\n")}
  These are ILLUSTRATIONS OF SHAPE from an unrelated conversation. Never reuse their words.
- If you cannot name what happened in THIS chunk that specifically, there is no beat: reply {"no_beat": true} instead of reaching for a remembered phrase.
- subject: the single name of the person this beat is ABOUT — whose inner state does the chunk reveal? Attribute the beat to the character whose emotion it is, not the speaker label. Use a name from the "Known characters" list when you are given one, or "user" for the human player.
${THREAD_RULE_SLOT}

Reply with only this JSON:
${dysreg ? JSON_FORMAT_WITH_SUBPATTERN : JSON_FORMAT_STANDARD}`;
}

