// ── Context window ─────────────────────────────────────────────────────────

export interface AnalysisContext {
  before?: ClassificationResult;
  after?: ClassificationResult;
}

// Prompt context beyond the chunk itself: who is in the scene, which threads
// are live, and what the scene is called (often the right new-thread label).
export interface AnalysisExtras {
  roster?: string[];
  threads?: string[];
  sceneTitle?: string;
  /** Only used to attribute a contamination event to a conversation. */
  chatId?: string;
}

function buildUserPrompt(result: ClassificationResult, context?: AnalysisContext, extras?: AnalysisExtras): string {
  const { chunk, scores, primaryEmotion, salience, structuralMatches } = result;
  const { roster, threads, sceneTitle } = extras ?? {};

  const rosterBlock = roster && roster.length > 0
    ? `Known characters (for the subject field): ${roster.join(", ")} — or "user" for the human player.\n\n`
    : "";

  const sceneLine = sceneTitle?.trim()
    // oknn: the caller now suppresses a title that names a person, so anything
    // reaching here describes a scene. The "never a person" clause stays as the
    // backstop — this line and the "never name the participants" rule above used
    // to contradict each other whenever the chat kept its default name, and the
    // later, more specific instruction won.
    ? `Scene name: "${sceneTitle.trim()}" — this names the SCENE, not a person. When a beat starts a NEW thread and this describes what is happening, prefer it as the thread label. If it is somebody's name, ignore it entirely and label the EVENT instead.\n\n`
    : "";

  const threadsBlock = threads && threads.length > 0
    ? `Active threads (for the thread field): ${threads.map((t) => `"${t}"`).join(", ")}\n\n`
    : "";

  const scoreLines = Object.entries(scores)
    .sort(([, a], [, b]) => b - a)
    .map(([e, s]) => `  ${e}: ${s.toFixed(2)}`)
    .join("\n");

  const structuralLines = structuralMatches.length > 0
    ? `\nStructural signals detected: ${structuralMatches.map(m => m.patternId).join(", ")}`
    : "";

  const beforeBlock = context?.before
    ? `Preceding context (${context.before.chunk.speaker} — for tone/intent reference only):
"""
${context.before.chunk.text.slice(0, 400)}${context.before.chunk.text.length > 400 ? "…" : ""}
"""

`
    : "";

  const afterBlock = context?.after
    ? `
Following context (${context.after.chunk.speaker} — for tone/intent reference only):
"""
${context.after.chunk.text.slice(0, 400)}${context.after.chunk.text.length > 400 ? "…" : ""}
"""`
    : "";

  return `${rosterBlock}${sceneLine}${threadsBlock}${beforeBlock}ANALYZE THIS — Speaker: ${chunk.speaker}
Primary emotion detected: ${primaryEmotion ?? "unknown"} (salience ${salience.toFixed(2)})
All emotion scores:
${scoreLines}${structuralLines}

Dialogue chunk:
"""
${chunk.text}
"""
${afterBlock}

Analyze the emotional beat in the chunk marked "ANALYZE THIS".`;
}

// ── Public API ─────────────────────────────────────────────────────────────

export async function analyzeChunk(
  result: ClassificationResult,
  context?: AnalysisContext,
  extras?: AnalysisExtras,
): Promise<BeatAnalysis | null> {
  if (!result.passesThreshold || !result.primaryEmotion) return null;

  const structuralSubpatterns = result.structuralMatches
    .map((m) => m.subpattern)
    .filter((s): s is string => Boolean(s));

  // The user prompt only carries an "Active threads" block when this is non-empty
  // (buildUserPrompt), so the system rule that cites that list is only reachable
  // under the same condition.
  const hasThreads = (extras?.threads?.length ?? 0) > 0;
  const systemPrompt = buildSystemPrompt(result.primaryEmotion, structuralSubpatterns, hasThreads);
  const userPrompt   = buildUserPrompt(result, context, extras);

  const raw = await callLlm(systemPrompt, userPrompt);
  const sourceText = result.chunk?.text ?? "";

  // TRIPWIRE. Fires on the SOURCE, not on the model's answer, because the leak event
  // is "bait vocabulary appeared in a chat" — which is upstream of, and independent
  // of, whether the model happened to echo it this time. Catching it here is what
  // makes rotation possible BEFORE the store absorbs a run of echoes, instead of
  // after, which is all scripts/bait-rot.mjs can offer.
  const tripped = detectBaitContamination(sourceText, listEchoEntries());
  for (const t of tripped) {
    recordContamination(getDataDir(), {
      at: new Date().toISOString(),
      entry: t.entry,
      words: t.words,
      chatId: extras?.chatId,
      excerpt: excerptAround(sourceText, t.words[0] ?? ""),
    });
  }

  // The chunk the model was asked about — the corroboration evidence for the echo
  // guard. Without it the guard cannot tell a copied example from a real utterance.
  // The exemption list is loaded here (memoised) rather than threaded through every
  // caller, because a caller that forgets it would convict REAL names — see epf4.
  const exempt = await knownNames();
  const analysis = parseAnalysisJson(raw, sourceText, exempt, extras?.chatId);
  return enforceSubtext(analysis, sourceText, systemPrompt, userPrompt, exempt, extras?.chatId);
}

/**
 * PROMPT ASKS, CODE ENFORCES (5x5y).
 *
 * The subtext field has been requested since May and emitted on 0.7% of the chunks
 * that warrant one — 11 times in 1,574 — because nothing ever checked. An optional
 * field an 8b model may silently skip is an advisory instruction, and this project
 * has ruled that advisory guards do no work.
 *
 * One retry, never two: a model that has now declined twice is telling us something,
 * and a third ask is how you talk a model into inventing. The original analysis is
 * kept and only the subtext is GRAFTED on, because the first answer's motivation and
 * outcome were fine — the retry exists to fill one gap, not to re-litigate the beat.
 */
export async function enforceSubtext(
  analysis: BeatAnalysis | null,
  sourceText: string,
  systemPrompt: string,
  userPrompt: string,
  exempt: string[] | null,
  chatId?: string,
  // Test seam. Production passes nothing and gets the real model call; a test passes
  // a stub and can assert HOW MANY TIMES it was called, which is the property that
  // matters most here — "one retry, never two" is a rule about call count.
  call: (system: string, user: string) => Promise<string | null> = callLlm,
): Promise<BeatAnalysis | null> {
  if (!analysis) return analysis;
  const verdict = classifyIntimacy(sourceText);
  if (!verdict.intimate) return analysis;

  const markers = [...verdict.strong, ...verdict.weak].slice(0, 6);
  const log = (outcome: SubtextOutcome) => recordSubtext(getDataDir(), {
    at: new Date().toISOString(),
    outcome,
    markers,
    chatId,
    excerpt: sourceText.replace(/\s+/g, " ").slice(0, 160),
  });

  if (analysis.subtext) { log("first-try"); return analysis; }

  const retryRaw = await call(systemPrompt, `${userPrompt}\n${SUBTEXT_RETRY}`);
  const retry = parseAnalysisJson(retryRaw, sourceText, exempt, chatId);
  if (!retry) { log("retry-failed"); return analysis; }
  if (!retry.subtext) { log("declined"); return analysis; }

  log("after-retry");
  return { ...analysis, subtext: retry.subtext };
}

export interface AnalyzedBeat {
  result:   ClassificationResult;
  analysis: BeatAnalysis;
}

// `targets` are the chunks to analyze (passing + speaker-filtered). `allChunks`
// is the full ordered classification list used purely for context — so the
// "preceding/following" blocks shown to the model are the TRUE adjacent chunks
// in the conversation, not the nearest other high-salience beat (which could be
// many turns away). Defaults to `targets` if not supplied.
// `onItem` (optional) is called after each chunk is processed — current is the
// 1-based index, total the count being analyzed, and reason is set only when the
// chunk failed (used by the story-import progress reporter).
export async function analyzeChunks(
  targets: ClassificationResult[],
  allChunks?: ClassificationResult[],
  onItem?: (current: number, total: number, reason?: string) => void,
  signal?: AbortSignal,
  extras?: AnalysisExtras,
): Promise<AnalyzedBeat[]> {
  const context = allChunks ?? targets;
  const passing = targets.filter((r) => r.passesThreshold && r.primaryEmotion);
  const total = passing.length;
  const output: AnalyzedBeat[] = [];

  let i = 0;
  for (const result of passing) {
    if (signal?.aborted) break; // cancelled — stop analyzing, keep what we have
    i++;
    const idx = context.indexOf(result);
    try {
      const analysis = await analyzeChunk(result, idx === -1 ? undefined : {
        before: context[idx - 1],
        after:  context[idx + 1],
      }, extras);
      if (analysis) {
        output.push({ result, analysis });
        onItem?.(i, total);
      } else {
        onItem?.(i, total, "model returned no parseable analysis");
      }
    } catch (err) {
      onItem?.(i, total, err instanceof Error ? err.message : String(err));
    }
  }

  return output;
}
