// ── Example echo guard (pifl) ────────────────────────────────────────────────
// Every phrase the prompt puts in front of the model as an illustration, good or
// bad. A motivation matching one is not an analysis of the chunk; it is the model
// returning what it was shown.
//
// THE LIST MUST INCLUDE THE RETIRED EXAMPLES, not just the current ones. The old
// wording is what 669 stored beats echo, so a store that is still being written to
// by an older build — or re-analysed — has to keep being caught. Deleting a line
// from here silently re-opens the hole it was closing.
// `probe` is what CORROBORATION looks for in the source text, and it is not the
// phrase itself. A real utterance is first person and differently worded — "i'm
// afraid the memory loss means i was never real" — so requiring the motivation's
// exact third-person phrasing would corroborate nothing and ban the sentence
// anyway. The probe is the distinctive core that survives rephrasing.
//
// Word boundaries matter here: /never real/ without \b also matches "never
// really", which is ordinary English and appears all over this store. That exact
// slip produced false hits during the investigation.
//
// Where a phrase is generic ("exposes her personal fear"), there is no meaningful
// core to probe for, so no probe is given and corroboration requires the literal
// phrase — which is the right bar for a sentence nobody actually says.
//
// `probeAll` IS THE ROT-RESISTANT FORM, AND IT REPLACES `probe` FOR NEW BAIT.
// A single-word probe is a warrant one ordinary noun can void. /\blocksmith\b/ was
// voided within a week — "locksmith" became a live thread label via an unrelated
// metaphor about sealed read paths — and the failure is structural, not unlucky:
// bait is MOST likely to be parroted on chunks about its own topic, which are
// exactly the chunks where the hatch opens. Guard strength was inversely correlated
// with risk. probeAll requires EVERY listed word in the source, and the words are
// chosen by anti-join against the whole corpus (scripts/bait-select.mjs), so voiding
// one takes a conversation that contains several words the store has never held.
export interface EchoEntry {
  phrase: string;
  /**
   * Shown in the prompt right now, as against retired-but-retained.
   *
   * The distinction drives whether a rotted warrant is an emergency or a footnote.
   * A CURRENT example with a corroborable probe is actively unguarded: the model is
   * being shown it every call and nothing will arrest it coming back. A RETIRED one
   * is not being taught any more, so its rot only weakens the catching of echoes
   * already in the store. Conflating them makes bait-rot permanently red — and a
   * check that is always failing is a check nobody reads, which is the failure mode
   * this guard exists to avoid in the first place.
   */
  current?: boolean;
  /** Legacy single-pattern corroboration. Rot-prone; kept for the retired entries. */
  probe?: RegExp;
  /** Corroborated only if EVERY word appears in the source text. */
  probeAll?: string[];
}

